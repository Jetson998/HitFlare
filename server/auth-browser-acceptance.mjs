const api = (page, path, method = "GET", body, extraHeaders = {}) => page.evaluate(async ({ path, method, body, extraHeaders }) => {
    const response = await fetch(path, { method, headers: { "content-type": "application/json", ...extraHeaders }, body: body === undefined ? undefined : JSON.stringify(body) });
    return { status: response.status, body: await response.json() };
}, { path, method, body, extraHeaders });
