const login = async (page, name, password = passwords[name]) => {
    await page.goto(`${base}/login`);
    await page.getByLabel("邮箱", { exact: true }).fill(`${name}@example.test`);
    await page.getByLabel("密码", { exact: true }).fill(password);
    await page.getByRole("button", { name: "登录", exact: true }).click();
    await page.waitForFunction(async email => {
        const { useUserStore } = await import("/src/stores/use-user-store.ts");
        return useUserStore.getState().user?.email === email;
    }, `${name}@example.test`);
    await page.waitForURL(url => url.pathname !== "/login");
    return state(page);
};
